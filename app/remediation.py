"""Generate reviewable scripts only. This module never calls Azure or a shell."""
import re
import shlex
from uuid import UUID


RESOURCE_ID = re.compile(
    r'^/subscriptions/([0-9a-fA-F-]{36})/resourceGroups/([A-Za-z0-9_.()-]{1,90})'
    r'/providers/(Microsoft\.Compute/disks|Microsoft\.Network/publicIPAddresses'
    r'|Microsoft\.Network/networkInterfaces|Microsoft\.Network/networkSecurityGroups'
    r'|Microsoft\.Network/applicationGateways)'
    r'/([A-Za-z0-9_.()-]{1,80})$', re.IGNORECASE)
RULE_TYPES = {
    'ORPHANED_DISK': 'microsoft.compute/disks',
    'UNASSOCIATED_PUBLIC_IP': 'microsoft.network/publicipaddresses',
    'ORPHANED_NIC': 'microsoft.network/networkinterfaces',
    'ORPHANED_NSG': 'microsoft.network/networksecuritygroups',
}


def generate_script(scan: dict, resource_ids: list[str], tenant_id: str,
                    subscription_ids: list[str]) -> str:
    """Caller supplies its authenticated tenant/subscriptions and owned scan.

    Only exact selected finding IDs are accepted. Azure authorization and approval
    remain the responsibility of the human executing the downloaded script.
    """
    if scan.get('mode') != 'azure' or scan.get('status') != 'completed' or scan.get('data_origin') == 'legacy_synthetic':
        raise ValueError('Remediation requires a completed live Azure scan')
    tenant_id = str(UUID(tenant_id))
    allowed = {str(UUID(s)) for s in subscription_ids}
    if not allowed:
        raise ValueError('No authorized subscriptions')
    if not isinstance(resource_ids, list) or not 1 <= len(resource_ids) <= 50:
        raise ValueError('Select between 1 and 50 resources')
    if any(not isinstance(rid, str) for rid in resource_ids) or len(set(resource_ids)) != len(resource_ids):
        raise ValueError('Select unique resource IDs')
    findings = {}
    for finding in scan.get('findings', []):
        rid = finding.get('resource_id')
        if rid in findings:
            raise ValueError('Scan contains duplicate resource identities')
        findings[rid] = finding
    selected = []
    for rid in resource_ids:
        finding = findings.get(rid)
        if finding is None:
            raise ValueError('Selected resource does not belong to this scan')
        rule = finding.get('rule_id')
        if rule not in RULE_TYPES:
            raise ValueError('Only unattached disks, public IPs, orphaned NICs, and NSGs support script generation')
        match = RESOURCE_ID.fullmatch(rid)
        if not match or match.group(3).lower() != RULE_TYPES[rule]:
            raise ValueError('Resource identity is invalid for the finding rule')
        subscription = str(UUID(match.group(1)))
        if subscription not in allowed or str(UUID(finding.get('subscription_id', ''))) != subscription:
            raise ValueError('Resource subscription is not authorized or does not match its finding')
        selected.append((rid, subscription, rule))

    lines = [
        '#!/usr/bin/env bash',
        'set -eu',
        '# Generated by CloudSaver. Review this entire file before running it.',
        '# DESTRUCTIVE: deletion permanently removes disk data or releases a public IP/NIC/NSG.',
        '# Confirm ownership, retention requirements and independent backups first.',
        '# Azure state can change between the final read and delete; rechecks are not atomic.',
        '# No resource is deleted without typing its complete resource ID interactively.',
        'command -v az >/dev/null 2>&1 || { echo "Azure CLI is required." >&2; exit 1; }',
        '[ -t 0 ] || { echo "Interactive terminal input is required." >&2; exit 1; }',
        'expected_tenant=' + shlex.quote(tenant_id),
        'active_tenant=$(az account show --query tenantId --output tsv)',
        '[ "$active_tenant" = "$expected_tenant" ] || { echo "Wrong Azure tenant." >&2; exit 1; }',
        'printf "%s\\n" "Review all deletions and backups before continuing."',
    ]
    for rid, subscription, rule in selected:
        lines.extend([
            '',
            'resource_id=' + shlex.quote(rid),
            'subscription_id=' + shlex.quote(subscription),
            'subscription_tenant=$(az account show --subscription "$subscription_id" --query tenantId --output tsv)',
            '[ "$subscription_tenant" = "$expected_tenant" ] || { echo "Subscription tenant mismatch." >&2; exit 1; }',
            'printf "\\nType this full resource ID to approve permanent deletion:\\n%s\\n> " "$resource_id"',
            'IFS= read -r confirmation',
            '[ "$confirmation" = "$resource_id" ] || { echo "Confirmation did not match. Aborting." >&2; exit 1; }',
        ])
        if rule == 'ORPHANED_DISK':
            lines.extend([
                'disk_state=$(az disk show --ids "$resource_id" --subscription "$subscription_id" --query diskState --output tsv)',
                '[ "$disk_state" = "Unattached" ] || { echo "Disk is no longer unattached. Aborting." >&2; exit 1; }',
                'az disk delete --ids "$resource_id" --subscription "$subscription_id" --yes',
            ])
        elif rule == 'UNASSOCIATED_PUBLIC_IP':
            lines.extend([
                "unassociated=$(az network public-ip show --ids \"$resource_id\" --subscription \"$subscription_id\" --query 'ipConfiguration.id == `null` && natGateway.id == `null`' --output tsv)",
                '[ "$unassociated" = "true" ] || { echo "Public IP has an association or its state is unknown. Aborting." >&2; exit 1; }',
                'az network public-ip delete --ids "$resource_id" --subscription "$subscription_id"',
            ])
        elif rule == 'ORPHANED_NIC':
            lines.extend([
                "unattached=$(az network nic show --ids \"$resource_id\" --subscription \"$subscription_id\" --query 'virtualMachine.id == `null` && privateEndpoint.id == `null`' --output tsv)",
                '[ "$unattached" = "true" ] || { echo "NIC is attached to a virtual machine or private endpoint. Aborting." >&2; exit 1; }',
                'az network nic delete --ids "$resource_id" --subscription "$subscription_id"',
            ])
        elif rule == 'ORPHANED_NSG':
            lines.extend([
                "unassociated=$(az network nsg show --ids \"$resource_id\" --subscription \"$subscription_id\" --query 'length(networkInterfaces) == `0` && length(subnets) == `0`' --output tsv)",
                '[ "$unassociated" = "true" ] || { echo "NSG is associated with subnets or interfaces. Aborting." >&2; exit 1; }',
                'az network nsg delete --ids "$resource_id" --subscription "$subscription_id"',
            ])
        lines.append('printf "Deleted: %s\\n" "$resource_id"')
    return '\n'.join(lines) + '\n'
